local function GetDamageType(kind)
    if kind == "physical" then return DAMAGE_TYPE_PHYSICAL end
    if kind == "pure" then return DAMAGE_TYPE_PURE end
    return DAMAGE_TYPE_MAGICAL
end

local function Special(ability, key, fallback)
    if not ability then return fallback or 0 end
    local value = ability:GetSpecialValueFor(key)
    if value == nil then return fallback or 0 end
    return value
end

function SurvivalAbility:GetIntrinsicModifierName(ability)
    local data = self.Data[ability:GetAbilityName()]
    if data and data.cast_type == "passive" then
        return "modifier_sirv_passive_core"
    end
    return nil
end

function SurvivalAbility:Cast(ability)
    local caster = ability:GetCaster()
    local data = self.Data[ability:GetAbilityName()]
    if not caster or not data then return end
    local cast = data.cast_type
    local damage = Special(ability, "damage", 0)
    local heal = Special(ability, "heal", 0)
    local radius = Special(ability, "radius", 300)
    local duration = Special(ability, "duration", 4)

    if cast == "target_damage" then
        local target = ability:GetCursorTarget()
        if target then
            ApplyDamage({ victim = target, attacker = caster, damage = damage, damage_type = GetDamageType(data.damage_type), ability = ability })
            self:PlayParticle(data.particle, target:GetAbsOrigin(), caster)
        end
        return
    end

    if cast == "target_heal" then
        local target = ability:GetCursorTarget() or caster
        target:Heal(heal, ability)
        self:PlayParticle(data.particle, target:GetAbsOrigin(), target)
        return
    end

    if cast == "heal_or_damage" then
        local target = ability:GetCursorTarget()
        if not target then return end
        if target:GetTeamNumber() == caster:GetTeamNumber() then
            target:Heal(heal, ability)
        else
            ApplyDamage({ victim = target, attacker = caster, damage = damage, damage_type = GetDamageType(data.damage_type), ability = ability })
        end
        self:PlayParticle(data.particle, target:GetAbsOrigin(), target)
        return
    end

    if cast == "target_shield" then
        local target = ability:GetCursorTarget() or caster
        target:AddNewModifier(caster, ability, "modifier_sirv_generic_shield", { duration = duration })
        if heal > 0 then target:Heal(heal, ability) end
        self:PlayParticle(data.particle, target:GetAbsOrigin(), target)
        return
    end

    if cast == "target_debuff" then
        local target = ability:GetCursorTarget()
        if target then
            if damage > 0 then
                ApplyDamage({ victim = target, attacker = caster, damage = damage, damage_type = GetDamageType(data.damage_type), ability = ability })
            end
            target:AddNewModifier(caster, ability, "modifier_sirv_generic_debuff", { duration = duration })
            self:PlayParticle(data.particle, target:GetAbsOrigin(), caster)
        end
        return
    end

    if cast == "point_aoe_damage" then
        local point = ability:GetCursorPosition()
        local enemies = FindUnitsInRadius(caster:GetTeamNumber(), point, nil, radius, DOTA_UNIT_TARGET_TEAM_ENEMY, DOTA_UNIT_TARGET_HERO + DOTA_UNIT_TARGET_BASIC, DOTA_UNIT_TARGET_FLAG_NONE, FIND_ANY_ORDER, false)
        for _, enemy in pairs(enemies) do
            ApplyDamage({ victim = enemy, attacker = caster, damage = damage, damage_type = GetDamageType(data.damage_type), ability = ability })
            if duration > 0 then enemy:AddNewModifier(caster, ability, "modifier_sirv_generic_debuff", { duration = duration }) end
        end
        self:PlayParticle(data.particle, point, caster)
        return
    end

    if cast == "point_aoe_heal" then
        local point = ability:GetCursorPosition()
        local allies = FindUnitsInRadius(caster:GetTeamNumber(), point, nil, radius, DOTA_UNIT_TARGET_TEAM_FRIENDLY, DOTA_UNIT_TARGET_HERO, DOTA_UNIT_TARGET_FLAG_NONE, FIND_ANY_ORDER, false)
        for _, ally in pairs(allies) do
            ally:Heal(heal, ability)
            ally:AddNewModifier(caster, ability, "modifier_sirv_generic_shield", { duration = duration })
        end
        self:PlayParticle(data.particle, point, caster)
        return
    end

    if cast == "no_target_damage" or cast == "no_target_debuff" then
        local enemies = FindUnitsInRadius(caster:GetTeamNumber(), caster:GetAbsOrigin(), nil, radius, DOTA_UNIT_TARGET_TEAM_ENEMY, DOTA_UNIT_TARGET_HERO + DOTA_UNIT_TARGET_BASIC, DOTA_UNIT_TARGET_FLAG_NONE, FIND_ANY_ORDER, false)
        for _, enemy in pairs(enemies) do
            if damage > 0 then
                ApplyDamage({ victim = enemy, attacker = caster, damage = damage, damage_type = GetDamageType(data.damage_type), ability = ability })
            end
            enemy:AddNewModifier(caster, ability, "modifier_sirv_generic_debuff", { duration = duration })
        end
        caster:AddNewModifier(caster, ability, "modifier_sirv_generic_buff", { duration = duration })
        self:PlayParticle(data.particle, caster:GetAbsOrigin(), caster)
        return
    end

    if cast == "no_target_heal" then
        local allies = FindUnitsInRadius(caster:GetTeamNumber(), caster:GetAbsOrigin(), nil, radius, DOTA_UNIT_TARGET_TEAM_FRIENDLY, DOTA_UNIT_TARGET_HERO, DOTA_UNIT_TARGET_FLAG_NONE, FIND_ANY_ORDER, false)
        for _, ally in pairs(allies) do
            ally:Heal(heal, ability)
            ally:AddNewModifier(caster, ability, "modifier_sirv_generic_shield", { duration = duration })
        end
        self:PlayParticle(data.particle, caster:GetAbsOrigin(), caster)
        return
    end

    if cast == "self_buff" or cast == "no_target_buff" then
        caster:AddNewModifier(caster, ability, "modifier_sirv_generic_buff", { duration = duration })
        self:PlayParticle("particles/items_fx/black_king_bar_avatar.vpcf", caster:GetAbsOrigin(), caster)
        return
    end

    if cast == "point_dash" then
        local point = ability:GetCursorPosition()
        local direction = point - caster:GetAbsOrigin()
        if direction:Length2D() > 600 then
            direction = direction:Normalized() * 600
            point = caster:GetAbsOrigin() + direction
        end
        ProjectileManager:ProjectileDodge(caster)
        FindClearSpaceForUnit(caster, point, true)
        caster:AddNewModifier(caster, ability, "modifier_sirv_generic_buff", { duration = duration })
        return
    end
end

function SurvivalAbility:PlayParticle(path, origin, owner)
    if not path or not origin then return end
    local particle = ParticleManager:CreateParticle(path, PATTACH_WORLDORIGIN, owner)
    ParticleManager:SetParticleControl(particle, 0, origin)
    ParticleManager:ReleaseParticleIndex(particle)
end

